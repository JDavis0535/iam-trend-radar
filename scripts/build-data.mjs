// build-data.mjs - generates the files that let the site run when index.html is opened directly (file://).
//   data/data.js  : window.IAM_DATA = {meta, taxonomy, trends, recommendations}   (from data/*.json)
//   dist/app.js   : classic (non-module) single-script bundle of js/**/*.js          (Chrome blocks ES modules on file://)
// Usage: node scripts/build-data.mjs [--data-only]      Re-run after editing data/*.json or js/**/*.js, then commit the outputs.
// The bundler is deliberately simple: it strips single-line `import ... from '...';` and `export` keywords,
// orders modules by dependency, wraps everything in one IIFE and fails on duplicate top-level names.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateDataset } from './validate-data.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = resolve(root, 'data');
const dataOnly = process.argv.includes('--data-only');

// ---- data bundle ----
const read = (f) => JSON.parse(readFileSync(resolve(dataDir, f), 'utf8'));
const data = { meta: read('meta.json'), taxonomy: read('taxonomy.json'), trends: read('trends.json'), recommendations: read('recommendations.json') };
const { errors } = validateDataset(data);
if (errors.length) {
  console.error(errors.map((e) => `ERROR ${e}`).join('\n'));
  console.error('Refusing to build: fix validation errors first.');
  process.exit(1);
}
// Escape "<" so no data value can ever close a script element.
const json = JSON.stringify(data, null, 1).replace(/</g, '\\u003c');
writeFileSync(resolve(dataDir, 'data.js'), `// GENERATED by scripts/build-data.mjs from data/*.json - do not edit by hand.\nwindow.IAM_DATA = ${json};\n`);
console.log('wrote data/data.js');

if (dataOnly) process.exit(0);

// ---- JS bundle (dependency order) ----
const order = [
  'js/filters.js', 'js/ui.js', 'js/export.js', 'js/store.js',
  'js/views/dashboard.js', 'js/views/trend.js', 'js/views/playbook.js', 'js/views/watchlist.js', 'js/views/feed.js', 'js/views/about.js',
  'js/router.js', 'js/app.js'
];
const seen = new Map();
const parts = [];
for (const rel of order) {
  let src = readFileSync(resolve(root, rel), 'utf8').replace(/\r\n/g, '\n');
  src = src.replace(/^import\s.*;$/gm, '');
  if (/^import\b/m.test(src)) throw new Error(`${rel}: multi-line import is not supported by the bundler`);
  src = src.replace(/^export\s+(async\s+function|function|const|let|class)\b/gm, '$1');
  if (/^export\b/m.test(src)) throw new Error(`${rel}: unsupported export form`);
  for (const m of src.matchAll(/^(?:async\s+)?(?:function|const|let|class)\s+([A-Za-z_$][\w$]*)/gm)) {
    if (seen.has(m[1])) throw new Error(`Duplicate top-level name "${m[1]}" in ${rel} and ${seen.get(m[1])}`);
    seen.set(m[1], rel);
  }
  parts.push(`/* ---- ${rel} ---- */\n${src.trim()}\n`);
}
const bundle = `// GENERATED by scripts/build-data.mjs from js/**/*.js - do not edit by hand.\n(function () {\n'use strict';\n${parts.join('\n')}})();\n`;
mkdirSync(resolve(root, 'dist'), { recursive: true });
writeFileSync(resolve(root, 'dist/app.js'), bundle);
console.log(`wrote dist/app.js (${bundle.length} bytes)`);
